/**
 * Bake the original SVG's expensive displacement filters into lossless sprites.
 * Run from src/frontend: node scripts/build-fracture-assets.mjs
 * Requires Chrome/Chromium (CHROME_PATH overrides discovery), Node 22+, and the
 * existing Next.js sharp dependency. No browser or image packages are added.
 */
import { spawn } from 'node:child_process';
import { readFile, writeFile, mkdtemp, rm, access } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const assetDir = path.join(root, 'public/fracture');
const artwork = await readFile(path.join(assetDir, 'artwork.svg'), 'utf8');
const candidates = [process.env.CHROME_PATH, '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', '/usr/bin/chromium', '/usr/bin/google-chrome'].filter(Boolean);
let chromePath;
for (const candidate of candidates) { try { await access(candidate); chromePath = candidate; break; } catch {} }
if (!chromePath) throw new Error('Install Chrome/Chromium or set CHROME_PATH.');
const profile = await mkdtemp(path.join(tmpdir(), 'fracture-bake-'));
const chrome = spawn(chromePath, ['--headless=new', '--disable-gpu', '--no-first-run', '--no-default-browser-check', '--remote-debugging-port=0', `--user-data-dir=${profile}`, 'about:blank'], { stdio: ['ignore', 'ignore', 'pipe'] });
let socket;
try {
  const endpoint = await new Promise((resolve, reject) => {
    let output = '';
    const timer = setTimeout(() => reject(new Error('Chrome startup timed out')), 20000);
    chrome.stderr.on('data', chunk => {
      output += chunk;
      const match = output.match(/DevTools listening on (ws:\/\/[^\s]+)/);
      if (match) { clearTimeout(timer); resolve(match[1]); }
    });
    chrome.on('error', reject);
  });
  const browserUrl = new URL(endpoint);
  const pages = await (await fetch(`http://${browserUrl.host}/json/list`)).json();
  socket = new WebSocket(pages.find(page => page.type === 'page').webSocketDebuggerUrl);
  await new Promise((resolve, reject) => { socket.onopen = resolve; socket.onerror = reject; });
  let sequence = 0;
  const pending = new Map();
  socket.onmessage = event => {
    const message = JSON.parse(event.data);
    const request = pending.get(message.id);
    if (!request) return;
    pending.delete(message.id);
    if (message.error) request.reject(new Error(message.error.message)); else request.resolve(message.result);
  };
  const send = (method, params) => new Promise((resolve, reject) => {
    const id = ++sequence;
    pending.set(id, { resolve, reject });
    socket.send(JSON.stringify({ id, method, params }));
  });
  const result = await send('Runtime.evaluate', { expression: `(${bakeInBrowser.toString()})(${JSON.stringify(artwork)})`, awaitPromise: true, returnByValue: true });
  if (result.exceptionDetails) throw new Error(JSON.stringify(result.exceptionDetails));
  const baked = result.result.value;
  await writeFile(path.join(assetDir, 'texture.svg'), baked.texture);
  let bytes = 0;
  let pixels = 0;
  for (const sprite of [...baked.pieces, baked.details]) {
    const png = Buffer.from(sprite.png.split(',')[1], 'base64');
    const webp = await sharp(png).webp({ lossless: true, effort: 6 }).toBuffer();
    const originalPixels = await sharp(png).ensureAlpha().raw().toBuffer();
    const encodedPixels = await sharp(webp).ensureAlpha().raw().toBuffer();
    for (let i = 0; i < originalPixels.length; i += 4) {
      if (originalPixels[i + 3] !== encodedPixels[i + 3] ||
          (originalPixels[i + 3] && (originalPixels[i] !== encodedPixels[i] || originalPixels[i + 1] !== encodedPixels[i + 1] || originalPixels[i + 2] !== encodedPixels[i + 2]))) {
        throw new Error(`Lossless encoding changed visible pixels in ${sprite.id}`);
      }
    }
    const name = `${sprite.id}.webp`;
    const retinaName = `${sprite.id}@2x.webp`;
    const standard = await sharp(png).resize(sprite.width, sprite.height).webp({ lossless: true, effort: 6 }).toBuffer();
    await writeFile(path.join(assetDir, name), standard);
    await writeFile(path.join(assetDir, retinaName), webp);
    sprite.src = `/fracture/${name}`;
    sprite.srcSet = `/fracture/${name} ${sprite.width}w, /fracture/${retinaName} ${sprite.width * 2}w`;
    delete sprite.png;
    bytes += webp.length + standard.length;
    pixels += sprite.width * sprite.height * 4;
  }
  const { src, srcSet, x, y, width, height } = baked.details;
  const manifest = `// Generated by scripts/build-fracture-assets.mjs; edit artwork.svg and rebuild.\nexport type FracturePoint = { x: number; y: number };\nexport type FractureSprite = { src: string; srcSet: string; x: number; y: number; width: number; height: number };\nexport type FractureAsset = FractureSprite & { id: string; angle: number; outline: FracturePoint[] };\nexport const FRACTURE_PIECES: FractureAsset[] = ${JSON.stringify(baked.pieces)};\nexport const FRACTURE_DETAILS: FractureSprite = ${JSON.stringify({src,srcSet,x,y,width,height})};\n`;
  await writeFile(path.join(root, 'src/components/desktop/fractureAssets.ts'), manifest);
  console.log(JSON.stringify({ sprites: baked.pieces.length + 1, imageFiles: (baked.pieces.length + 1) * 2, bytes, decodedBytes1x: pixels, decodedBytes2x: pixels * 4, outlines: baked.pieces.reduce((total, piece) => total + piece.outline.length, 0) }, null, 2));
} finally {
  socket?.close();
  chrome.kill();
  await new Promise(resolve => chrome.once('exit', resolve));
  await rm(profile, { recursive: true, force: true });
}

async function bakeInBrowser(source) {
  const sourceSvg = new DOMParser().parseFromString(source, 'image/svg+xml').documentElement;
  if (sourceSvg.querySelector('parsererror')) throw new Error('Invalid artwork SVG');
  document.body.append(sourceSvg);
  const children = [...sourceSvg.children];
  const defs = children[0];
  const textureGroup = children[1];
  const branchesGroup = children[2];
  const detailGroup = children[3];
  const serializer = new XMLSerializer();
  const rootFor = group => {
    const svg = sourceSvg.cloneNode(false);
    svg.append(defs.cloneNode(true), group.cloneNode(true));
    return svg;
  };
  const texture = serializer.serializeToString(rootFor(textureGroup));
  const render = async (group, id) => {
    const box = group.getBBox();
    // The 12-unit displacement moves pixels at most 6 units in each direction;
    // extra padding includes the red highlight stroke and anti-aliased edges.
    const x = Math.floor(box.x - 10), y = Math.floor(box.y - 10);
    const width = Math.ceil(box.x + box.width + 10) - x;
    const height = Math.ceil(box.y + box.height + 10) - y;
    const svg = rootFor(group);
    svg.lastElementChild.removeAttribute('mask');
    svg.setAttribute('viewBox', `${x} ${y} ${width} ${height}`);
    svg.setAttribute('width', String(width * 2));
    svg.setAttribute('height', String(height * 2));
    const img = new Image();
    img.src = `data:image/svg+xml;charset=utf-8,${encodeURIComponent(serializer.serializeToString(svg))}`;
    await img.decode();
    const canvas = document.createElement('canvas');
    canvas.width = width * 2; canvas.height = height * 2;
    canvas.getContext('2d').drawImage(img, 0, 0);
    return { id, x, y, width, height, png: canvas.toDataURL('image/png') };
  };
  const pieces = [];
  for (const group of branchesGroup.children) {
    const id = group.getAttribute('data-piece');
    // Offshoots belong to the same bitmap and hit geometry as their parent branch.
    const paths = [...defs.querySelectorAll(`#fracture-${id} path`), ...group.querySelectorAll('[data-offshoot] path')];
    const primaryPaths = [...defs.querySelectorAll(`#fracture-${id} path`)];
    const outline = paths.flatMap(path => {
      const length = path.getTotalLength();
      const steps = Math.max(1, Math.ceil(length / 12));
      return Array.from({length: steps + 1}, (_, index) => {
        const point = path.getPointAtLength(length * index / steps);
        return { x: +point.x.toFixed(2), y: +point.y.toFixed(2) };
      });
    });
    // Keep the parent's radial axis independent of its fine offshoots.
    const primaryPoints = primaryPaths.flatMap(path => {
      const length = path.getTotalLength();
      const steps = Math.max(1, Math.ceil(length / 12));
      return Array.from({ length: steps + 1 }, (_, i) => path.getPointAtLength(length * i / steps));
    });
    const furthest = primaryPoints.reduce((best, point) => Math.hypot(point.x-800, point.y-500) > Math.hypot(best.x-800, best.y-500) ? point : best);
    const angle = +(Math.atan2(furthest.y - 500, furthest.x - 800) * 180 / Math.PI).toFixed(3);
    pieces.push({ ...await render(group, id), angle, outline });
  }
  return { texture, pieces, details: await render(detailGroup, 'details') };
}
